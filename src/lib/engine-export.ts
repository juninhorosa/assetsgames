import { zipSync, strToU8 } from "fflate";
import { buildAgentGuide, buildManifest } from "./ai-pack";
import { dataUrlToBytes, type FrameRect, type MapType } from "./image-pipeline";
import { isPixelStyle, type AssetMode, type StyleProfile } from "./style-profile";
import { resolvePreset, type ExportPreset, type PivotPreset } from "./export-presets";

export type Engine = "unity" | "unreal" | "godot";

export const ENGINE_LABELS: Record<Engine, string> = {
  unity: "Unity",
  unreal: "Unreal Engine",
  godot: "Godot",
};

export interface AssetExport {
  name: string;
  mode: AssetMode;
  style: StyleProfile;
  prompt: string;
  /** albedo/base image */
  image: string;
  maps?: Partial<Record<MapType, string>> | undefined;
  frames?: string[] | undefined;
  frameRects?: FrameRect[] | undefined;
  animation?:
    | { name: string; label?: string | undefined; fps: number; columns: number; rows: number }
    | undefined;
  /** extra binary files (GLB meshes) keyed by path inside the pack */
  models?: Record<string, Uint8Array> | undefined;
  /** stop-motion 3D metadata, when a 3D movement was generated */
  motion3d?:
    | { fps: number; frameCount: number; depth: number; segments: number; style?: string | undefined }
    | undefined;
  tileset?: { tileSize: number; columns: number; rows: number; kind: string } | undefined;
}

function slug(name: string) {
  return (
    name
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "_")
      .replace(/^_|_$/g, "") || "asset"
  );
}

function metadata(asset: AssetExport, engine: Engine) {
  return {
    generator: "Forge3D Asset Studio",
    version: 1,
    engine,
    name: asset.name,
    slug: slug(asset.name),
    assetType: asset.mode,
    prompt: asset.prompt,
    style: asset.style,
    maps: Object.keys(asset.maps ?? {}),
    animation: asset.animation
      ? {
          ...asset.animation,
          frameCount: asset.frames?.length ?? 0,
          frames: asset.frameRects ?? [],
        }
      : null,
    tileset: asset.tileset ?? null,
  };
}

const UNITY_ALIGNMENT: Record<PivotPreset, string> = {
  "bottom-center": "SpriteAlignment.BottomCenter",
  center: "SpriteAlignment.Center",
  "top-left": "SpriteAlignment.TopLeft",
};

function unityImporter(asset: AssetExport, preset: ExportPreset) {
  const id = slug(asset.name);
  const isSheet = asset.mode === "spritesheet" && asset.animation;
  return `// Auto-generated by Forge3D Asset Studio.
// Preset: ${preset.label} — ${preset.unit}, pivô ${preset.pivot}, ${preset.pixelsPerUnit} px/unidade.
// Drop this file in Assets/Editor/ and the asset imports with the right settings.
using System.Collections.Generic;
using System.IO;
using UnityEditor;
using UnityEngine;

public class Forge3D_${id}_Importer : AssetPostprocessor
{
    const string AssetFolder = "${preset.paths.root}/${id}";

    void OnPreprocessTexture()
    {
        if (!assetPath.StartsWith(AssetFolder)) return;
        var importer = (TextureImporter)assetImporter;
        importer.alphaIsTransparency = true;
        importer.spritePixelsPerUnit = ${preset.pixelsPerUnit};
        importer.mipmapEnabled = ${preset.importer.mipmaps ? "true" : "false"};
        importer.wrapMode = TextureWrapMode.${preset.importer.wrap === "repeat" ? "Repeat" : "Clamp"};
        importer.filterMode = FilterMode.${preset.importer.filterMode === "point" ? "Point" : "Bilinear"};
        importer.textureCompression = TextureImporterCompression.${preset.importer.compression === "none" ? "Uncompressed" : "Compressed"};
        importer.sRGBTexture = true;

        var file = Path.GetFileNameWithoutExtension(assetPath);
        // Dados lineares (roughness/metallic/ao/height) não usam sRGB.
        if (file.EndsWith("roughness") || file.EndsWith("metallic") || file.EndsWith("ao") || file.EndsWith("height"))
            importer.sRGBTexture = false;
        if (file.EndsWith("normal")) importer.textureType = TextureImporterType.NormalMap;
${
  isSheet
    ? `
        if (file == "${id}_sheet")
        {
            importer.textureType = TextureImporterType.Sprite;
            importer.spriteImportMode = SpriteImportMode.Multiple;
            var meta = new List<SpriteMetaData>();
            int cols = ${asset.animation!.columns}, rows = ${asset.animation!.rows};
            int cw = ${asset.frameRects?.[0]?.w ?? 0}, ch = ${asset.frameRects?.[0]?.h ?? 0};
            for (int r = 0; r < rows; r++)
                for (int c = 0; c < cols; c++)
                    meta.Add(new SpriteMetaData {
                        name = "${id}_" + (r * cols + c),
                        rect = new Rect(c * cw, (rows - 1 - r) * ch, cw, ch),
                        alignment = (int)${UNITY_ALIGNMENT[preset.pivot]}
                    });
            importer.spritesheet = meta.ToArray();
        }`
    : ""
}
    }
}
`;
}


function unrealScript(asset: AssetExport, preset: ExportPreset) {
  const id = slug(asset.name);
  const maps = Object.keys(asset.maps ?? {});
  return `# Auto-generated by Forge3D Asset Studio.
# Preset: ${preset.label} — ${preset.unit}, up ${preset.upAxis}, malhas ×${preset.meshScale}.
# Run inside Unreal: Tools > Execute Python Script.
import unreal, os

SOURCE_DIR = os.path.dirname(os.path.abspath(__file__))
DEST = "${preset.paths.root}/${id}"
MAPS = ${JSON.stringify(maps)}
MESH_SCALE = ${preset.meshScale}
LINEAR_MAPS = ["roughness", "metallic", "ao", "height"]

def import_textures():
    tasks = []
    for m in MAPS:
        path = os.path.join(SOURCE_DIR, "textures", "${id}_%s.png" % m)
        if not os.path.exists(path):
            continue
        task = unreal.AssetImportTask()
        task.filename = path
        task.destination_path = DEST
        task.automated = True
        task.replace_existing = True
        task.save = True
        tasks.append(task)
    unreal.AssetToolsHelpers.get_asset_tools().import_asset_tasks(tasks)

    # Espaço de cor: só o albedo é sRGB; o resto é dado linear.
    for m in MAPS:
        tex = unreal.EditorAssetLibrary.load_asset("%s/${id}_%s" % (DEST, m))
        if not tex:
            continue
        if m in LINEAR_MAPS:
            tex.set_editor_property("srgb", False)
        if m == "normal":
            tex.set_editor_property("compression_settings", unreal.TextureCompressionSettings.TC_NORMALMAP)
        unreal.EditorAssetLibrary.save_loaded_asset(tex)

def import_meshes():
    mesh_dir = os.path.join(SOURCE_DIR, "meshes")
    if not os.path.isdir(mesh_dir):
        return
    for f in os.listdir(mesh_dir):
        if not f.lower().endswith(".glb"):
            continue
        task = unreal.AssetImportTask()
        task.filename = os.path.join(mesh_dir, f)
        task.destination_path = DEST
        task.automated = True
        task.replace_existing = True
        task.save = True
        opts = unreal.FbxImportUI()
        opts.import_as_skeletal = False
        task.options = opts
        unreal.AssetToolsHelpers.get_asset_tools().import_asset_tasks([task])

def build_material():
    tools = unreal.AssetToolsHelpers.get_asset_tools()
    mat = tools.create_asset("M_${id}", DEST, unreal.Material, unreal.MaterialFactoryNew())
    mat.set_editor_property("blend_mode", unreal.BlendMode.${preset.material.alphaCutout ? "BLEND_MASKED" : "BLEND_TRANSLUCENT"})
    slots = {"albedo": "BaseColor", "normal": "Normal", "roughness": "Roughness",
             "metallic": "Metallic", "ao": "AmbientOcclusion"}
    y = -400
    for m, prop in slots.items():
        if m not in MAPS:
            continue
        tex = unreal.EditorAssetLibrary.load_asset("%s/${id}_%s" % (DEST, m))
        if not tex:
            continue
        node = unreal.MaterialEditingLibrary.create_material_expression(
            mat, unreal.MaterialExpressionTextureSample, -400, y)
        node.texture = tex
        unreal.MaterialEditingLibrary.connect_material_property(
            node, "RGB", getattr(unreal.MaterialProperty, "MP_" + prop.upper()))
        y += 200
    unreal.MaterialEditingLibrary.recompile_material(mat)

import_textures()
import_meshes()
build_material()
unreal.log("Forge3D: ${asset.name} imported (scale %s)." % MESH_SCALE)
`;
}


function godotMaterial(asset: AssetExport, preset: ExportPreset) {
  const id = slug(asset.name);
  const root = preset.paths.root;
  const maps = asset.maps ?? {};
  const lines: string[] = [];
  const ext: string[] = [];
  let n = 1;
  const push = (map: MapType, prop: string) => {
    if (!maps[map]) return;
    ext.push(
      `[ext_resource type="Texture2D" path="${root}/${id}/textures/${id}_${map}.png" id="${n}"]`,
    );
    lines.push(`${prop} = ExtResource("${n}")`);
    n++;
  };
  push("albedo", "albedo_texture");
  push("normal", "normal_texture");
  push("roughness", "roughness_texture");
  push("metallic", "metallic_texture");
  push("ao", "ao_texture");
  push("height", "heightmap_texture");

  return `; Auto-generated by Forge3D Asset Studio.
; Preset: ${preset.label} — ${preset.unit}, pivô ${preset.pivot}.
[gd_resource type="StandardMaterial3D" load_steps=${n} format=3]

${ext.join("\n")}

[resource]
resource_name = "${asset.name}"
${lines.join("\n")}
${preset.material.alphaCutout ? "transparency = 2\nalpha_scissor_threshold = 0.5" : "transparency = 1"}
texture_filter = ${preset.importer.filterMode === "point" ? "0" : "1"}
texture_repeat = ${preset.importer.wrap === "repeat" ? "true" : "false"}
${maps.normal ? "normal_enabled = true" : ""}
${maps.ao ? "ao_enabled = true" : ""}
${maps.height ? "heightmap_enabled = true" : ""}
uv1_scale = Vector3(1, 1, 1)
`;
}


function godotSpriteFrames(asset: AssetExport, preset: ExportPreset) {
  const id = slug(asset.name);

  const anim = asset.animation!;
  const rects = asset.frameRects ?? [];
  const frames = rects
    .map(
      (r, i) =>
        `{
"duration": 1.0,
"texture": SubResource("Atlas${i}")
}`,
    )
    .join(", ");
  const subs = rects
    .map(
      (r, i) => `[sub_resource type="AtlasTexture" id="Atlas${i}"]
atlas = ExtResource("1")
region = Rect2(${r.x}, ${r.y}, ${r.w}, ${r.h})
`,
    )
    .join("\n");
  return `; Auto-generated by Forge3D Asset Studio.
[gd_resource type="SpriteFrames" load_steps=${rects.length + 2} format=3]

[ext_resource type="Texture2D" path="${preset.paths.root}/${id}/${id}_sheet.png" id="1"]

${subs}
[resource]
animations = [{
"frames": [${frames}],
"loop": true,
"name": &"${anim.name}",
"speed": ${anim.fps}.0
}]
`;
}

function readme(asset: AssetExport, engine: Engine, preset: ExportPreset) {
  const id = slug(asset.name);
  const steps: Record<Engine, string> = {
    unity: `1. Copie a pasta \`textures/\` (e \`frames/\`, se houver) para \`${preset.paths.root}/${id}/\`.
2. Copie \`Forge3D_${id}_Importer.cs\` para \`Assets/Editor/\`.
3. Reimporte a pasta: as texturas ganham alpha, wrap e filtro corretos automaticamente.`,
    unreal: `1. Copie esta pasta inteira para um local acessível do projeto.
2. No Unreal: Tools > Execute Python Script > \`import_${id}.py\`.
3. As texturas entram em \`${preset.paths.root}/${id}\` e o material \`M_${id}\` é montado com os mapas PBR.`,
    godot: `1. Copie a pasta para \`${preset.paths.root}/${id}/\`.
2. O Godot importa os PNGs automaticamente.
3. Use \`${id}_material.tres\` em um MeshInstance3D${asset.animation ? ` ou \`${id}_frames.tres\` em um AnimatedSprite2D` : ""}.`,
  };
  return `# ${asset.name} — ${ENGINE_LABELS[engine]}

Gerado pelo Forge3D Asset Studio.

- Tipo: ${asset.mode}
- Estilo: ${asset.style.style}
- Prompt: ${asset.prompt}

## Preset aplicado — ${preset.label}

- Escala: ${preset.unit} (malhas ×${preset.meshScale}, up ${preset.upAxis})
- Pivô: ${preset.pivot} · ${preset.pixelsPerUnit} px por unidade
- Material: ${preset.material.shader} (${preset.material.alphaCutout ? "alpha cutout" : "alpha blend"}, normal ${preset.material.normalSpace})
- Caminho de destino: \`${preset.paths.root}/${id}\`
${preset.notes.map((n) => `- ${n}`).join("\n")}

## Importação

${steps[engine]}
`;
}


/**
 * Builds an engine-ready ZIP (textures, meshes, metadata, import script) that
 * always carries the AI-readable manifest + agent guide.
 * `engine === null` produces the engine-agnostic "pacote para IA" (all scripts).
 */
export function buildEngineZip(
  asset: AssetExport,
  engine: Engine | null,
  options: { pivot?: PivotPreset } = {},
): Blob {
  const zipped = zipSync(buildEngineFiles(asset, engine, options), { level: 6 });
  return new Blob([zipped as unknown as BlobPart], { type: "application/zip" });
}

/**
 * Same content as {@link buildEngineZip}, but returned as a flat file map so
 * several assets can be merged into a single archive (biblioteca / exportação
 * em lote).
 */
export function buildEngineFiles(
  asset: AssetExport,
  engine: Engine | null,
  options: { pivot?: PivotPreset } = {},
): Record<string, Uint8Array> {
  const id = slug(asset.name);
  const files: Record<string, Uint8Array> = {};

  const preset = resolvePreset(engine ?? "unity", {
    pixelArt: isPixelStyle(asset.style.style) || asset.mode === "tileset",
    tiling: asset.mode === "texture" || asset.mode === "tileset",
    pivot: options.pivot,
  });


  const maps = asset.maps ?? {};
  for (const [map, dataUrl] of Object.entries(maps)) {
    if (!dataUrl) continue;
    files[`textures/${id}_${map}.png`] = dataUrlToBytes(dataUrl);
  }
  if (!maps.albedo) files[`textures/${id}_albedo.png`] = dataUrlToBytes(asset.image);

  if (asset.animation) {
    files[`${id}_sheet.png`] = dataUrlToBytes(asset.image);
    (asset.frames ?? []).forEach((frame, i) => {
      files[`frames/${id}_${String(i).padStart(2, "0")}.png`] = dataUrlToBytes(frame);
    });
    files["frames.json"] = strToU8(
      JSON.stringify(
        {
          image: `${id}_sheet.png`,
          columns: asset.animation.columns,
          rows: asset.animation.rows,
          cellWidth: asset.frameRects?.[0]?.w ?? 0,
          cellHeight: asset.frameRects?.[0]?.h ?? 0,
          animations: [
            {
              name: asset.animation.name,
              fps: asset.animation.fps,
              loop: true,
              frames: asset.frameRects ?? [],
            },
          ],
        },
        null,
        2,
      ),
    );
  }

  if (asset.tileset) {
    files[`${id}_tileset.png`] = dataUrlToBytes(asset.image);
    files["tileset.json"] = strToU8(JSON.stringify({
      image: `${id}_tileset.png`,
      ...asset.tileset,
      tileCount: asset.tileset.columns * asset.tileset.rows,
      readOrder: "left-to-right, top-to-bottom",
    }, null, 2));
  }

  for (const [path, bytes] of Object.entries(asset.models ?? {})) {
    files[path] = bytes;
  }

  files["forge3d.json"] = strToU8(JSON.stringify(metadata(asset, engine ?? "unity"), null, 2));
  files["forge3d.preset.json"] = strToU8(
    JSON.stringify(
      engine
        ? preset
        : (["unity", "unreal", "godot"] as Engine[]).reduce<Record<string, ExportPreset>>(
            (acc, e) => {
              acc[e] = presetFor(e);
              return acc;
            },
            {},
          ),
      null,
      2,
    ),
  );

  // Cada script nasce com o preset da sua própria engine, mesmo no pacote para IA.
  function presetFor(e: Engine): ExportPreset {
    return resolvePreset(e, {
      pixelArt: isPixelStyle(asset.style.style) || asset.mode === "tileset",
      tiling: asset.mode === "texture" || asset.mode === "tileset",
      pivot: options.pivot,
    });
  }

  if (engine === "unity" || engine === null) {
    files[`Forge3D_${id}_Importer.cs`] = strToU8(unityImporter(asset, presetFor("unity")));
  }
  if (engine === "unreal" || engine === null) {
    files[`import_${id}.py`] = strToU8(unrealScript(asset, presetFor("unreal")));
  }
  if (engine === "godot" || engine === null) {
    const godot = presetFor("godot");
    files[`${id}_material.tres`] = strToU8(godotMaterial(asset, godot));
    if (asset.animation) files[`${id}_frames.tres`] = strToU8(godotSpriteFrames(asset, godot));
  }


  const cell = asset.frameRects?.[0];
  const manifest = buildManifest({
    name: asset.name,
    slug: id,
    mode: asset.mode,
    prompt: asset.prompt,
    style: asset.style,
    engine,
    paths: [...Object.keys(files), "forge3d.manifest.json", "AGENTS.md"].sort(),
    maps: Object.keys(maps),
    animation: asset.animation
      ? {
          name: asset.animation.name,
          label: asset.animation.label,
          fps: asset.animation.fps,
          columns: asset.animation.columns,
          rows: asset.animation.rows,
          cellWidth: cell?.w ?? 0,
          cellHeight: cell?.h ?? 0,
          frameCount: asset.frames?.length ?? 0,
          rects: asset.frameRects ?? [],
        }
      : undefined,
    motion3d: asset.motion3d,
  });
  files["forge3d.manifest.json"] = strToU8(JSON.stringify(manifest, null, 2));
  files["AGENTS.md"] = strToU8(buildAgentGuide(manifest));
  files["README.md"] = strToU8(readme(asset, engine ?? "unity", preset));

  return files;
}


export function downloadBlob(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  a.click();
  setTimeout(() => URL.revokeObjectURL(url), 2000);
}

export function downloadDataUrl(dataUrl: string, filename: string) {
  const a = document.createElement("a");
  a.href = dataUrl;
  a.download = filename;
  a.click();
}

